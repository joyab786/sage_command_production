class StateIngestRequest(BaseModel):
    """Request to ingest a state observation into the Digital Twin."""
    model_config = ConfigDict(extra="ignore")

    entity_id: str = Field(..., min_length=1)
    properties: List[Dict[str, Any]] = Field(..., min_length=1, description="List of property dicts with name, value, value_type, etc.")
    classification: TwinStateClassification = Field(default=TwinStateClassification.OBSERVED)
    source_type: FactSourceType = Field(default=FactSourceType.TELEMETRY)
    source_id: str = Field(default="system")
    observed_at: Optional[str] = None
    effective_at: Optional[str] = None
    confidence: TwinConfidence = Field(default=TwinConfidence.UNKNOWN)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class SnapshotCreateRequest(BaseModel):
    """Request to create a point-in-time snapshot."""
    model_config = ConfigDict(extra="ignore")

    snapshot_timestamp: Optional[str] = None  # Defaults to now
    entity_ids: Optional[List[str]] = None  # None = all twin entities
    description: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ScenarioCreateRequest(BaseModel):
    """Request to create a simulation scenario."""
    model_config = ConfigDict(extra="ignore")

    base_snapshot_id: str = Field(..., min_length=1)
    name: str = Field(..., min_length=1, max_length=256)
    description: Optional[str] = None
    overrides: List[Dict[str, Any]] = Field(default_factory=list, description="[{entity_id, property_name, value, value_type}]")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class StateCompareRequest(BaseModel):
    """Request to compare two twin states."""
    model_config = ConfigDict(extra="ignore")

    source_type: str = Field(..., description="snapshot | entity | scenario")
    source_id: str = Field(...)
    target_type: str = Field(..., description="snapshot | entity | scenario")
    target_id: str = Field(...)


class TwinEntityResponse(BaseModel):
    success: bool = True
    data: TwinEntity
    message: Optional[str] = None


class TwinHistoryResponse(BaseModel):
    success: bool = True
    data: List[TwinStateVersion]
    total_count: int


class SnapshotResponse(BaseModel):
    success: bool = True
    data: TwinSnapshot
    message: Optional[str] = None


class ScenarioResponse(BaseModel):
    success: bool = True
    data: TwinScenario
    message: Optional[str] = None


class CompareResponse(BaseModel):
    success: bool = True
    diffs: List[TwinStateDiff]
    total_changes: int


class ValidationResponse(BaseModel):
    success: bool = True
    report: TwinValidationReport
